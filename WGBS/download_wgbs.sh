    # Skip if already downloaded
    if [ -f "$OUT_DIR/${SRR}.fastq" ]; then
        echo "Already exists, skipping: $SRR"
        continue
    fi

    echo ">>> Downloading: $SRR"

    # Download
    prefetch $SRR

    # Convert to fastq
    fasterq-dump $SRR --outdir $OUT_DIR --split-files

    # Cleanup all temp and prefetch files
    rm -rf $OUT_DIR/${SRR}/
    rm -f $OUT_DIR/${SRR}.sra
    rm -f $OUT_DIR/${SRR}.sra.tmp
    rm -f $OUT_DIR/${SRR}.sra.lock
    rm -f $OUT_DIR/${SRR}.sra.prf
    rm -rf $SRR

    echo "<<< Done: $SRR (cleaned up)"
done

echo "ALL 95 WGBS SAMPLES DOWNLOADED AND CLEANED!"
